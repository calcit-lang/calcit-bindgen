    #[test]
    fn renders_typed_db_bindings_and_rejects_drifted_shapes() {
        let rendered = render(&db_document())
            .expect("validate db contract")
            .expect("db artifacts must be generated");
        assert!(rendered.rust_adapter.contains("wasmtime_db"));
        assert!(rendered.calcit_bindings.contains("defmacro query-as"));
        assert!(
            rendered
                .calcit_bindings
                .contains("try-decode-map-as parsed (List ~row-type)")
        );
        assert!(
            !rendered.calcit_bindings.contains("; Schema:"),
            "signatures must live in CodeEntry :schema entries, not comments"
        );
        assert_eq!(rendered.wit, WASI_DB_WIT);

        let snapshot = cirru_edn::parse(&rendered.calcit_bindings)
            .expect("generated db_bindings.cirru must parse as Cirru EDN Snapshot");
        let cirru_edn::Edn::Map(root) = &snapshot else {
            panic!("Snapshot root must be a map");
        };
        let files = root
            .get_or_nil("files")
            .view_map()
            .expect("Snapshot :files map");
        let file_entry = match &files.0[&cirru_edn::Edn::sym("generated.demo.db")] {
            cirru_edn::Edn::Struct(view) => view,
            other => panic!("expected FileEntry struct, got {other}"),
        };
        let defs_edn = file_entry
            .pairs
            .iter()
            .find(|(k, _)| k.ref_str() == "defs")
            .map(|(_, v)| v)
            .expect(":defs in FileEntry");
        let defs = defs_edn.view_map().expect(":defs map");

        for expected_import in [
            "sql-query",
            "sql-exec",
            "tx-begin",
            "tx-query",
            "tx-exec",
            "tx-commit",
            "tx-rollback",
            "kv-get",
            "kv-set",
            "kv-delete",
        ] {
            let entry = match &defs.0[&cirru_edn::Edn::sym(expected_import)] {
                cirru_edn::Edn::Struct(view) => view,
                other => panic!("{expected_import} must be a CodeEntry struct, got {other}"),
            };
            let schema = entry
                .pairs
                .iter()
                .find(|(k, _)| k.ref_str() == "schema")
                .map(|(_, v)| v)
                .unwrap_or_else(|| panic!("{expected_import} is missing :schema"));
            let cirru_edn::Edn::Quote(cirru) = schema else {
                panic!("{expected_import} :schema must be a quoted Cirru form, got {schema}");
            };
            let formatted = format!("{cirru}");
            assert!(
                formatted.contains("Fn") && formatted.contains("generated.demo.db/DbError"),
                "{expected_import} :schema must carry typed Fn signature returning Result<_, DbError>, got: {formatted}"
            );
        }

        for nominal in ["DbParam", "DbError", "DbExecResult", "DbQueryResult"] {
            assert!(defs.0.contains_key(&cirru_edn::Edn::sym(nominal)));
        }
        for macro_name in ["query-as", "tx-query-as"] {
            let entry = match &defs.0[&cirru_edn::Edn::sym(macro_name)] {
                cirru_edn::Edn::Struct(view) => view,
                other => panic!("{macro_name} must be a CodeEntry struct, got {other}"),
            };
            let schema = entry
                .pairs
                .iter()
                .find(|(k, _)| k.ref_str() == "schema")
                .map(|(_, v)| v)
                .unwrap_or_else(|| panic!("{macro_name} is missing :schema"));
            assert!(matches!(schema, cirru_edn::Edn::Quote(_)));
        }

        let mut drifted = db_document();
        let Declaration::Enum { variants, .. } = &mut drifted.declarations[0] else {
            panic!("DbParam must be an enum")
        };
        variants.swap(0, 1);
        assert!(
            render(&drifted)
                .expect_err("reject reordered DbParam variants")
                .contains("DbParam")
        );

        let mut async_db = db_document();
        async_db.definitions[0].invocation = Some(ComponentInvocation::Async);
        assert!(
            render(&async_db)
                .expect_err("reject async calcit:db import")
                .contains("synchronous")
        );
    }
