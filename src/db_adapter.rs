pub const WASI_DB_WIT: &str = include_str!("wasi_db_wit/db.wit");
pub const DB_SQL_INSTANCE: &str = "calcit:db/sql@0.1.0";
pub const DB_KV_INSTANCE: &str = "calcit:db/kv@0.1.0";

const RUST_ADAPTER: &str = r#"// Generated by calcit-bindgen. Do not edit.
// Enable calcit-bindgen's `wasmtime-db` feature in the host crate.

pub use calcit_bindgen::wasmtime_db::{
    DbConfig, DbError, DbExecResult, DbParam, DbQueryResult, HttpDbServiceRunner,
    InMemoryKvBackend, KvBackend, ServiceHttpResponse, SqlBackend, SqliteSqlBackend,
    WasmtimeDbState, add_to_linker,
};
"#;

#[derive(Debug)]
pub(crate) struct DbRenderedArtifacts {
    pub rust_adapter: String,
    pub wit: String,
    pub calcit_bindings: String,
}

pub(crate) fn render(document: &ComponentDocument) -> Result<Option<DbRenderedArtifacts>, String> {
    let candidates = document
        .definitions
        .iter()
        .filter(|definition| {
            matches!(
                definition.module.as_deref(),
                Some(DB_SQL_INSTANCE | DB_KV_INSTANCE)
            )
        })
        .collect::<Vec<_>>();
    if candidates.is_empty() {
        return Ok(None);
    }

    let declarations = document
        .declarations
        .iter()
        .map(|declaration| (declaration.id(), declaration))
        .collect::<BTreeMap<_, _>>();

    let mut seen_symbols = BTreeSet::new();
    let mut db_error_id: Option<String> = None;
    let mut db_param_id: Option<String> = None;
    let mut db_query_result_id: Option<String> = None;
    let mut db_exec_result_id: Option<String> = None;

    for definition in &candidates {
        let module = definition
            .module
            .as_deref()
            .expect("filtered DB definition has a module");
        if definition.direction != ComponentDirection::Import
            || definition.invocation != Some(ComponentInvocation::Sync)
            || definition.status != DefinitionStatus::Supported
        {
            return Err(format!(
                "{} must be a supported synchronous Component import",
                definition.id
            ));
        }
        if !seen_symbols.insert((module, definition.symbol.as_str())) {
            return Err(format!(
                "{}.{} must not be declared more than once",
                module, definition.symbol
            ));
        }
        let signature = definition.signature.as_ref().ok_or_else(|| {
            format!(
                "{} ({module}.{}) must provide a closed Component signature",
                definition.id, definition.symbol
            )
        })?;
        validate_db_definition(
            definition,
            module,
            signature,
            &declarations,
            &mut db_error_id,
            &mut db_param_id,
            &mut db_query_result_id,
            &mut db_exec_result_id,
        )?;
    }

    let package = kebab(&document.package)?;
    let calcit_namespace = format!("generated.{}.db", package.replace('-', "."));
    let calcit_bindings = render_calcit_db_bindings(&calcit_namespace)?;

    Ok(Some(DbRenderedArtifacts {
        rust_adapter: RUST_ADAPTER.to_owned(),
        wit: WASI_DB_WIT.to_owned(),
        calcit_bindings,
    }))
}

/// Render a standalone typed Calcit bindings module for `calcit:db@0.1.0`.
pub fn render_calcit_db_bindings(namespace: &str) -> Result<String, String> {
    validate_calcit_namespace(namespace)?;
    let mut out = String::new();
    writeln!(
        out,
        "; Generated by calcit-bindgen for calcit:db@0.1.0. Do not edit.\n\nns {namespace}\n  :require\n"
    )
    .expect("write to String");
    out.push_str(
        r#"; Nominal WIT types (variants and fields strictly in alphabetical order matching Canonical ABI).
defenum DbParam (:bool-value Bool) (:bytes-value Buffer) (:float-value Float64) (:int-value Int64) (:null-value) (:text-value String)

defenum DbError (:backend String) (:capability-denied String) (:constraint-violation String) (:decode-error String) (:invalid-query String) (:timeout String) (:tx-error String) (:unsupported String)

defstruct DbExecResult (:last-insert-id (Option Int64)) (:rows-affected UInt64)

defstruct DbQueryResult (:columns (List String)) (:rows-json String)

; Synchronous WIT imports under calcit:db/sql@0.1.0
; Schema: Fn String (List DbParam) (-> (Result DbQueryResult DbError))
defwasm-import sql-query (sql params) |calcit:db/sql@0.1.0 |query

; Schema: Fn String (List DbParam) (-> (Result DbExecResult DbError))
defwasm-import sql-exec (sql params) |calcit:db/sql@0.1.0 |exec

; Schema: Fn (-> (Result UInt64 DbError))
defwasm-import tx-begin () |calcit:db/sql@0.1.0 |tx-begin

; Schema: Fn UInt64 String (List DbParam) (-> (Result DbQueryResult DbError))
defwasm-import tx-query (tx-id sql params) |calcit:db/sql@0.1.0 |tx-query

; Schema: Fn UInt64 String (List DbParam) (-> (Result DbExecResult DbError))
defwasm-import tx-exec (tx-id sql params) |calcit:db/sql@0.1.0 |tx-exec

; Schema: Fn UInt64 (-> (Result Unit DbError))
defwasm-import tx-commit (tx-id) |calcit:db/sql@0.1.0 |tx-commit

; Schema: Fn UInt64 (-> (Result Unit DbError))
defwasm-import tx-rollback (tx-id) |calcit:db/sql@0.1.0 |tx-rollback

; Synchronous WIT imports under calcit:db/kv@0.1.0
; Schema: Fn String (-> (Result (Option Buffer) DbError))
defwasm-import kv-get (key) |calcit:db/kv@0.1.0 |get

; Schema: Fn String Buffer (Option UInt64) (-> (Result Unit DbError))
defwasm-import kv-set (key value ttl-ms) |calcit:db/kv@0.1.0 |set

; Schema: Fn String (-> (Result Bool DbError))
defwasm-import kv-delete (key) |calcit:db/kv@0.1.0 |delete

; Decode closed JSON row payloads directly into Result (List RowStruct) DbError
; so Dynamic values never escape into application logic.
defmacro query-as (sql params row-type)
  quasiquote $ match (sql-query ~sql ~params)
    (:err db-err) (Result :err db-err)
    (:ok res)
      match (try-parse-json (:rows-json res))
        (:err reason) (Result :err (DbError :decode-error reason))
        (:ok parsed)
          match (try-decode-map-as parsed (List ~row-type))
            (:err reason) (Result :err (DbError :decode-error reason))
            (:ok rows) (Result :ok rows)

defmacro tx-query-as (tx-id sql params row-type)
  quasiquote $ match (tx-query ~tx-id ~sql ~params)
    (:err db-err) (Result :err db-err)
    (:ok res)
      match (try-parse-json (:rows-json res))
        (:err reason) (Result :err (DbError :decode-error reason))
        (:ok parsed)
          match (try-decode-map-as parsed (List ~row-type))
            (:err reason) (Result :err (DbError :decode-error reason))
            (:ok rows) (Result :ok rows)
"#,
    );
    Ok(out)
}

#[allow(clippy::too_many_arguments)]
fn validate_db_definition(
    definition: &ComponentDefinition,
    module: &str,
    signature: &FunctionSignature,
    declarations: &BTreeMap<&str, &Declaration>,
    db_error_id: &mut Option<String>,
    db_param_id: &mut Option<String>,
    db_query_result_id: &mut Option<String>,
    db_exec_result_id: &mut Option<String>,
) -> Result<(), String> {
    let context = format!("{} ({module}.{})", definition.id, definition.symbol);
    let (ok_type, error_type) = match &signature.result {
        Type::Result { ok, error } => (ok.as_ref(), error.as_ref()),
        _ => {
            return Err(format!("{context} must return Result<_, DbError>"));
        }
    };
    let error_id = nominal_id(error_type, "enum", &context, "DbError")?;
    ensure_db_error_enum(declarations, error_id, &context)?;
    pin_shared_id(db_error_id, error_id, "DbError", &context)?;

    match (module, definition.symbol.as_str()) {
        (DB_SQL_INSTANCE, "query") => {
            require_params(signature, 2, &context)?;
            require_type(
                &signature.parameters[0].type_ir,
                &Type::String,
                "sql",
                &context,
            )?;
            let param_id = list_item_nominal(
                &signature.parameters[1].type_ir,
                "enum",
                "params",
                &context,
                "DbParam",
            )?;
            ensure_db_param_enum(declarations, param_id, &context)?;
            pin_shared_id(db_param_id, param_id, "DbParam", &context)?;
            let query_id = nominal_id(ok_type, "struct", &context, "DbQueryResult")?;
            ensure_db_query_result_struct(declarations, query_id, &context)?;
            pin_shared_id(db_query_result_id, query_id, "DbQueryResult", &context)?;
        }
        (DB_SQL_INSTANCE, "exec") => {
            require_params(signature, 2, &context)?;
            require_type(
                &signature.parameters[0].type_ir,
                &Type::String,
                "sql",
                &context,
            )?;
            let param_id = list_item_nominal(
                &signature.parameters[1].type_ir,
                "enum",
                "params",
                &context,
                "DbParam",
            )?;
            ensure_db_param_enum(declarations, param_id, &context)?;
            pin_shared_id(db_param_id, param_id, "DbParam", &context)?;
            let exec_id = nominal_id(ok_type, "struct", &context, "DbExecResult")?;
            ensure_db_exec_result_struct(declarations, exec_id, &context)?;
            pin_shared_id(db_exec_result_id, exec_id, "DbExecResult", &context)?;
        }
        (DB_SQL_INSTANCE, "tx-begin") => {
            require_params(signature, 0, &context)?;
            require_type(ok_type, &Type::Uint64, "result.ok", &context)?;
        }
        (DB_SQL_INSTANCE, "tx-query") => {
            require_params(signature, 3, &context)?;
            require_type(
                &signature.parameters[0].type_ir,
                &Type::Uint64,
                "tx-id",
                &context,
            )?;
            require_type(
                &signature.parameters[1].type_ir,
                &Type::String,
                "sql",
                &context,
            )?;
            let param_id = list_item_nominal(
                &signature.parameters[2].type_ir,
                "enum",
                "params",
                &context,
                "DbParam",
            )?;
            ensure_db_param_enum(declarations, param_id, &context)?;
            pin_shared_id(db_param_id, param_id, "DbParam", &context)?;
            let query_id = nominal_id(ok_type, "struct", &context, "DbQueryResult")?;
            ensure_db_query_result_struct(declarations, query_id, &context)?;
            pin_shared_id(db_query_result_id, query_id, "DbQueryResult", &context)?;
        }
        (DB_SQL_INSTANCE, "tx-exec") => {
            require_params(signature, 3, &context)?;
            require_type(
                &signature.parameters[0].type_ir,
                &Type::Uint64,
                "tx-id",
                &context,
            )?;
            require_type(
                &signature.parameters[1].type_ir,
                &Type::String,
                "sql",
                &context,
            )?;
            let param_id = list_item_nominal(
                &signature.parameters[2].type_ir,
                "enum",
                "params",
                &context,
                "DbParam",
            )?;
            ensure_db_param_enum(declarations, param_id, &context)?;
            pin_shared_id(db_param_id, param_id, "DbParam", &context)?;
            let exec_id = nominal_id(ok_type, "struct", &context, "DbExecResult")?;
            ensure_db_exec_result_struct(declarations, exec_id, &context)?;
            pin_shared_id(db_exec_result_id, exec_id, "DbExecResult", &context)?;
        }
        (DB_SQL_INSTANCE, "tx-commit" | "tx-rollback") => {
            require_params(signature, 1, &context)?;
            require_type(
                &signature.parameters[0].type_ir,
                &Type::Uint64,
                "tx-id",
                &context,
            )?;
            require_type(ok_type, &Type::Unit, "result.ok", &context)?;
        }
        (DB_KV_INSTANCE, "get") => {
            require_params(signature, 1, &context)?;
            require_type(
                &signature.parameters[0].type_ir,
                &Type::String,
                "key",
                &context,
            )?;
            require_type(
                ok_type,
                &Type::Option {
                    item: Box::new(Type::Buffer),
                },
                "result.ok",
                &context,
            )?;
        }
        (DB_KV_INSTANCE, "set") => {
            require_params(signature, 3, &context)?;
            require_type(
                &signature.parameters[0].type_ir,
                &Type::String,
                "key",
                &context,
            )?;
            require_type(
                &signature.parameters[1].type_ir,
                &Type::Buffer,
                "value",
                &context,
            )?;
            require_type(
                &signature.parameters[2].type_ir,
                &Type::Option {
                    item: Box::new(Type::Uint64),
                },
                "ttl-ms",
                &context,
            )?;
            require_type(ok_type, &Type::Unit, "result.ok", &context)?;
        }
        (DB_KV_INSTANCE, "delete") => {
            require_params(signature, 1, &context)?;
            require_type(
                &signature.parameters[0].type_ir,
                &Type::String,
                "key",
                &context,
            )?;
            require_type(ok_type, &Type::Bool, "result.ok", &context)?;
        }
        _ => {
            return Err(format!(
                "{context}: unsupported symbol under calcit:db@0.1.0"
            ));
        }
    }

    Ok(())
}

fn validate_calcit_namespace(namespace: &str) -> Result<(), String> {
    if namespace.is_empty()
        || namespace.starts_with('.')
        || namespace.ends_with('.')
        || namespace.contains("..")
        || !namespace
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b'.'))
    {
        return Err(format!(
            "invalid Calcit namespace for DB bindings: {namespace:?}"
        ));
    }
    Ok(())
}

fn pin_shared_id(
    slot: &mut Option<String>,
    candidate: &str,
    label: &str,
    context: &str,
) -> Result<(), String> {
    if let Some(existing) = slot.as_deref() {
        if existing != candidate {
            return Err(format!(
                "{context} mixes {label} declaration {candidate} with {existing}"
            ));
        }
    } else {
        *slot = Some(candidate.to_owned());
    }
    Ok(())
}

fn require_params(
    signature: &FunctionSignature,
    expected: usize,
    context: &str,
) -> Result<(), String> {
    if signature.parameters.len() != expected
        || signature
            .parameters
            .iter()
            .enumerate()
            .any(|(index, parameter)| parameter.position != index)
    {
        return Err(format!(
            "{context} must accept {expected} positional parameters"
        ));
    }
    Ok(())
}

fn require_type(actual: &Type, expected: &Type, path: &str, context: &str) -> Result<(), String> {
    if actual != expected {
        return Err(format!(
            "{context} parameter/result `{path}` does not match calcit:db@0.1.0"
        ));
    }
    Ok(())
}

fn nominal_id<'a>(
    value: &'a Type,
    kind: &str,
    context: &str,
    expected_name: &str,
) -> Result<&'a str, String> {
    match (kind, value) {
        ("struct", Type::Struct { id, arguments }) | ("enum", Type::Enum { id, arguments })
            if arguments.is_empty() =>
        {
            Ok(id)
        }
        _ => Err(format!(
            "{context} must reference a monomorphic {expected_name} {kind}"
        )),
    }
}

fn list_item_nominal<'a>(
    value: &'a Type,
    kind: &str,
    path: &str,
    context: &str,
    expected_name: &str,
) -> Result<&'a str, String> {
    match value {
        Type::List { item } => nominal_id(item, kind, context, expected_name),
        _ => Err(format!(
            "{context} parameter `{path}` must be a list of monomorphic {expected_name}"
        )),
    }
}

fn ensure_db_param_enum(
    declarations: &BTreeMap<&str, &Declaration>,
    id: &str,
    context: &str,
) -> Result<(), String> {
    let variants = enum_variants(declarations, id, "DbParam", context)?;
    require_variants(
        variants,
        &[
            ("bool-value", vec![Type::Bool]),
            ("bytes-value", vec![Type::Buffer]),
            ("float-value", vec![Type::Float64]),
            ("int-value", vec![Type::Int64]),
            ("null-value", vec![]),
            ("text-value", vec![Type::String]),
        ],
        "DbParam",
    )
}

