fn struct_fields<'a>(
    declarations: &BTreeMap<&str, &'a Declaration>,
    id: &str,
    expected_name: &str,
    context: &str,
) -> Result<&'a [StructField], String> {
    match declarations.get(id) {
        Some(Declaration::Struct {
            name,
            type_parameters,
            fields,
            ..
        }) if name == expected_name && type_parameters.is_empty() => Ok(fields),
        _ => Err(format!(
            "{context} requires a monomorphic {expected_name} struct at {id}"
        )),
    }
}

fn enum_variants<'a>(
    declarations: &BTreeMap<&str, &'a Declaration>,
    id: &str,
    expected_name: &str,
    context: &str,
) -> Result<&'a [EnumVariant], String> {
    match declarations.get(id) {
        Some(Declaration::Enum {
            name,
            type_parameters,
            variants,
            ..
        }) if name == expected_name && type_parameters.is_empty() => Ok(variants),
        _ => Err(format!(
            "{context} requires a monomorphic {expected_name} enum at {id}"
        )),
    }
}

fn require_fields(
    actual: &[StructField],
    expected: &[(&str, Type)],
    name: &str,
) -> Result<(), String> {
    if actual.len() != expected.len()
        || actual
            .iter()
            .zip(expected)
            .any(|(field, (field_name, field_type))| {
                field.name != *field_name || field.type_ir != *field_type
            })
    {
        return Err(format!(
            "{name} does not match the calcit:db@0.1.0 contract"
        ));
    }
    Ok(())
}

fn require_variants(
    actual: &[EnumVariant],
    expected: &[(&str, Vec<Type>)],
    name: &str,
) -> Result<(), String> {
    if actual.len() != expected.len()
        || actual
            .iter()
            .zip(expected)
            .any(|(variant, (variant_name, payload))| {
                variant.name != *variant_name || variant.payload != *payload
            })
    {
        return Err(format!(
            "{name} does not match the calcit:db@0.1.0 contract"
        ));
    }
    Ok(())
}

